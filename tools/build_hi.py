#!/usr/bin/env python3
"""Builds js/hi.js (Hindi dictionary) from tools/hi_static.json + tools/hi_native.json. Keys are lower-cased, whitespace-collapsed."""
import json,os,re
r=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d={}
for f in ('hi_static.json','hi_native.json','hi_extra.json'):
    p=r+'/tools/'+f
    if os.path.exists(p):
        for k,v in json.load(open(p,encoding='utf-8')).items(): d[re.sub(r'\s+',' ',k).strip().lower()]=v
open(r+'/js/hi.js','w',encoding='utf-8').write('/* Hindi dictionary - generated by tools/build_hi.py, do not edit. Wording needs a native-speaker review. */\nwindow.HI='+json.dumps(d,ensure_ascii=False,separators=(',',':'))+';\n')
print(len(d),'Hindi strings')
